export type AccountText = (key: AccountTextKey, values?: Record<string, string>) => string;

export function accountTextFor(language: Language): AccountText {
  const table = language === 'zh' ? zh : en;
  return (key, values) => {
    let text: string = table[key];
    if (values) for (const [name, value] of Object.entries(values)) text = text.replace(`{${name}}`, value);
    return text;
  };
}
