package org.agentos.audio

private class Driver : AudioDriver {
    lateinit var sink: AudioDriver.Sink
    var finishes=0; var closes=0
    val texts=mutableListOf<String>()
    override fun submit(index: Long,text: String){texts.add(text)}
    override fun start(sink: AudioDriver.Sink) { this.sink=sink }
    override fun finish() { finishes++ }
    override fun close() { closes++ }
}
fun main() {
    val drivers=mutableListOf<Driver>()
    val runtime=AudioRuntime { Driver().also { drivers.add(it) } }
    val events=mutableListOf<AudioEvent>()
    val id=runtime.open("owner",AudioRequest(),events::add)
    val driver=drivers.last()
    check(events.single().phase==AudioPhase.Preparing)
    check(runtime.resources("owner").busy && runtime.resources("owner").ownedByCaller)
    check(!runtime.resources("other").ownedByCaller && runtime.resources("other").purpose=="DICTATION")
    driver.sink.ready();driver.sink.text("你好",false)
    runtime.finish("owner",id);runtime.finish("owner",id)
    check(driver.finishes==1)
    driver.sink.text("你好世界",true);driver.sink.released();driver.sink.completed()
    check(events.last().phase==AudioPhase.Closed && events.last().completion=="complete")
    check(!runtime.resources("owner").busy && runtime.resources("owner").previousRestoreConfirmed==true)
    check(events.filter{it.type=="Text"}.last().final)
    check(events.all{it.monotonicMs>0})
    check(events.map{it.sequence}==events.indices.map{it+1L})
    check(runCatching{runtime.status("other",id)}.exceptionOrNull() is AudioFailure)
    val next=runtime.open("owner",AudioRequest(),events::add);val d=drivers.last()
    check(runCatching{runtime.open("other",AudioRequest(),events::add)}.exceptionOrNull() is AudioFailure)
    runtime.close("owner",next)
    check(runtime.status("owner",next).phase==AudioPhase.Stopping)
    check(runtime.resources("owner").busy && runtime.resources("owner").phase==AudioPhase.Stopping)
    d.sink.ready();d.sink.text("迟到",true)
    check(events.none{it.text=="迟到"})
    d.sink.released();check(runtime.status("owner",next).restored)
    val third=runtime.open("owner",AudioRequest(),events::add);runtime.revoke("POLICY_REVOKED");drivers.last().sink.released()
    check(runtime.status("owner",third).reason=="POLICY_REVOKED")
    val lease=runtime.open("legacy",AudioRequest(purpose="LEGACY_REALTIME"),events::add)
    runtime.revoke("POLICY_REVOKED");check(runtime.status("legacy",lease).phase==AudioPhase.Stopping)
    runtime.disconnect("legacy");check(runtime.status("legacy",lease).phase==AudioPhase.Closed)
    val spoken=AudioRequest(purpose="SPEAK",profileId="kokoro",language="en-US")
    val speech=runtime.open("reader",spoken,events::add,"same-request")
    check(runtime.open("reader",spoken,events::add,"same-request")==speech)
    check(runCatching{runtime.open("reader",spoken.copy(speed=2f),events::add,"same-request")}.exceptionOrNull() is AudioFailure)
    val tts=drivers.last()
    runtime.append("reader",speech,0,"Hello")
    runtime.append("reader",speech,0,"Hello")
    check(tts.texts==listOf("Hello"))
    check(runCatching{runtime.append("reader",speech,0,"Different")}.exceptionOrNull() is AudioFailure)
    check(runCatching{runtime.append("reader",speech,2,"Gap")}.exceptionOrNull() is AudioFailure)
    runtime.finish("reader",speech);check(tts.finishes==1)
    tts.sink.ready();check(runtime.status("reader",speech).phase==AudioPhase.Draining)
    tts.sink.playback(0,"chunkComplete",24000,24000,true)
    tts.sink.released();tts.sink.completed()
    check(runtime.status("reader",speech).completion=="complete")
    check(runtime.open("reader",spoken,events::add,"same-request")==speech)
    check(SpeechChunks.split("字".repeat(1200)).all{it.length<=240})
    check(SpeechChunks.split("A sentence. ".repeat(100)).joinToString(" ").contains("sentence"))
    val sentences=SpeechChunks.Stream()
    check(sentences.accept("你好，",false).isEmpty())
    check(sentences.accept("你好，世界。下一句",false)==listOf("你好，世界。"))
    check(sentences.accept("你好，世界。下一句",false).isEmpty())
    check(sentences.accept("你好，世界。下一句完成",true)==listOf("下一句完成"))
    check(sentences.finished)
    val decimal=SpeechChunks.Stream()
    check(decimal.accept("The value is 3.",false).isEmpty())
    check(decimal.accept("The value is 3.14. Next",false)==listOf("The value is 3.14."))
    val interrupt=runtime.open("conversation",spoken.copy(interruptible=true),events::add)
    val talking=drivers.last();talking.sink.ready()
    runtime.append("conversation",interrupt,0,"First answer.")
    talking.sink.interrupted();talking.sink.interrupted()
    check(talking.finishes==1 && events.count{it.sessionId==interrupt && it.type=="Interrupted"}==1)
    check(runtime.status("conversation",interrupt).phase==AudioPhase.Draining && runtime.resources("conversation").busy)
    check((runCatching{runtime.append("conversation",interrupt,1,"Late answer.")}.exceptionOrNull() as AudioFailure).code=="INPUT_CLOSED")
    talking.sink.text("Wait",false);talking.sink.text("Wait, another question.",true)
    check(events.last().final && events.last().text=="Wait, another question.")
    talking.sink.released();check(runtime.resources("conversation").busy)
    talking.sink.completed()
    check(runtime.status("conversation",interrupt).reason=="interrupted" && runtime.status("conversation",interrupt).completion=="incomplete")
    check(!runtime.resources("conversation").busy && runtime.status("conversation",interrupt).restored)
    check(runCatching{runtime.open("wrong-purpose",AudioRequest(interruptible=true),events::add)}.exceptionOrNull() is AudioFailure)
    val media=AudioRequest(purpose="MEDIA_TRANSLATE",language="en-US",targetLanguage="zh-CN",targetPackage="com.android.chrome")
    val video=runtime.open("video",media,events::add);val cloud=drivers.last()
    cloud.sink.ready();cloud.sink.translation("一杯咖啡",true)
    check(events.last().textKind=="target" && events.last().direction=="incoming")
    cloud.sink.inputEnded();check(runtime.status("video",video).phase==AudioPhase.Draining && cloud.finishes==1)
    runtime.revokeProfiles(setOf("fal-kotoba"),"PROVIDER_REMOVED");cloud.sink.released()
    check(runtime.status("video",video).reason=="PROVIDER_REMOVED")
    val local=runtime.open("local",AudioRequest(),events::add);val asr=drivers.last();asr.sink.ready()
    runtime.revokeProfiles(setOf("fal-kotoba"),"PROVIDER_REMOVED");check(runtime.status("local",local).phase==AudioPhase.Running)
    runtime.close("local",local);asr.sink.released(false)
    check(!runtime.status("local",local).restored && runtime.status("local",local).reason=="RESTORE_FAILED")
    check(runtime.resources("local").previousRestoreConfirmed==false)
    val phone=media.copy(purpose="CALL_TRANSLATE",profileId="local-hybrid",output="SPEECH",originalAudio="REPLACE",outgoingProfileId="fal-grok",outgoingVoiceId="eve")
    val call=runtime.open("phone",phone,events::add);val twoWay=drivers.last();twoWay.sink.ready()
    twoWay.sink.directionalText("outgoing","target","Hello",true)
    check(events.last().direction=="outgoing" && events.last().textKind=="target")
    runtime.revokeProfiles(AudioProfiles.fal,"PROVIDER_REMOVED");twoWay.sink.released()
    check(runtime.status("phone",call).reason=="PROVIDER_REMOVED")
    val captions=media.copy(profileId="fal-whisper")
    check(runCatching{runtime.open("captions",captions.copy(output="SPEECH"),events::add)}.exceptionOrNull() is AudioFailure)
    check(runCatching{runtime.open("captions",captions.copy(purpose="CALL_TRANSLATE"),events::add)}.exceptionOrNull() is AudioFailure)
    val captionSession=runtime.open("captions",captions,events::add);drivers.last().sink.ready()
    runtime.revokeProfiles(AudioProfiles.fal,"PROVIDER_REMOVED");drivers.last().sink.released()
    check(runtime.status("captions",captionSession).reason=="PROVIDER_REMOVED")
    val segments=mutableListOf<FileSpeechSegments.Segment>();val segmenter=FileSpeechSegments(segments::add)
    val continuous=ShortArray(160000){(1000+it%997).toShort()}
    for(offset in continuous.indices step 320)segmenter.accept(continuous.copyOfRange(offset,minOf(continuous.size,offset+320)))
    segmenter.finish()
    check(segments.all{it.pcm.size<=64000})
    val restored=segments.flatMap{if(it.overlapping)it.pcm.drop(16000)else it.pcm.toList()}.toShortArray()
    check(restored.contentEquals(continuous)) // Continuous speech survives maximum-length boundaries and finish.
    segments.clear();segmenter.accept(ShortArray(3200){1000});check(segments.isEmpty());segmenter.finish();check(segments.single().pcm.size==3200)
    val overlap=CaptionOverlap();check(overlap.fresh("Hello world",false)=="Hello world");check(overlap.fresh("world again",true)=="again");check(overlap.fresh("again",false)=="again")
    val chinese=CaptionOverlap();chinese.fresh("我想喝咖啡",false);check(chinese.fresh("喝咖啡然后散步",true)=="然后散步")
    println("PASS: audio lifecycle, ownership, resource exclusion, cancellation, scoped revocation, restoration failures, request/chunk deduplication and bounded speech chunks")
}
