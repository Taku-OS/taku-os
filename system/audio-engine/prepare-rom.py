#!/usr/bin/env python3
"""Stage and seal the Audio Engine APK, CLI bridge and read-only ASR/TTS pack."""
import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import runpy
import shutil
import struct
import subprocess
import zipfile

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
PREFIX = 'system/audio-engine/'
VOICES_DIR = 'tts/espeak-ng-data/voices/!v/'
SPACED_VOICE = VOICES_DIR + 'Mr serious'
SAFE_VOICE = VOICES_DIR + 'Mr_serious'
VOICES_BLUEPRINT = PREFIX + 'prebuilt/Android.bp'
spec = importlib.util.spec_from_file_location('rom_formats', ROOT / 'system/ai/rom_formats.py')
formats = importlib.util.module_from_spec(spec)
spec.loader.exec_module(formats)


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def ordinary(root, name):
    path = root / name
    if (Path(name).is_absolute() or '..' in Path(name).parts or not path.is_file()
            or any(p.is_symlink() for p in (path, *path.parents) if p != root.parent)
            or not path.resolve().is_relative_to(root.resolve())):
        raise ValueError('Expected ordinary contained input: ' + name)
    return path


def installed_model_name(name):
    """Return a build-safe install path while retaining sealed upstream content."""
    if name == SPACED_VOICE:
        return SAFE_VOICE
    if any(c.isspace() for c in name):
        raise ValueError('Unexpected whitespace in model path: ' + name)
    return name


def source_names(root):
    module = root / PREFIX
    names = [str(p.relative_to(root)) for folder in ('src', 'contract', 'client', 'res', 'models', 'network', 'permissions')
             for p in (module / folder).rglob('*') if p.is_file() and '__pycache__' not in p.parts
             and p.name != 'rom-files.mk']
    names += [PREFIX + n for n in ('Android.bp', 'AndroidManifest.xml', 'build.sh', 'record-build.py',
                                   'prepare-rom.py', 'verify-rom.py')]
    names += [VOICES_BLUEPRINT]
    names += ['scripts/android-env.sh', 'scripts/kotlin-env.sh', 'scripts/aosp-test-keys.py', 'system/ai/rom_formats.py']
    return sorted(names)


def apk_entries(apk):
    with zipfile.ZipFile(apk) as archive, Path(apk).open('rb') as stream:
        if len(archive.namelist()) != len(set(archive.namelist())) or archive.testzip():
            raise ValueError('APK duplicate entries or CRC failure')
        entries = {}
        native_count = 0
        for info in archive.infolist():
            if info.is_dir() or info.filename.startswith('META-INF/'):
                continue
            raw = archive.read(info)
            entries[info.filename] = hashlib.sha256(raw).hexdigest()
            if info.filename.startswith('lib/'):
                if not re.fullmatch(r'lib/arm64-v8a/[^/]+\.so', info.filename):
                    raise ValueError('Unexpected JNI ABI or path')
                native_count += 1
                stream.seek(info.header_offset)
                name_length, extra_length = struct.unpack_from('<HH', stream.read(30), 26)
                offset = info.header_offset + 30 + name_length + extra_length
                elf = formats.elf_info(raw)
                if (info.compress_type != zipfile.ZIP_STORED or offset % 16384
                        or elf['machine'] != 183 or elf['loadAlignment'] < 16384):
                    raise ValueError('JNI must be arm64, stored, ZIP and ELF 16KB aligned: ' + info.filename)
        if not native_count:
            raise ValueError('Missing speech JNI libraries')
        return entries


def model_makefile(files):
    # Soong derives PRODUCT_COPY_FILES module names from directory paths. The
    # upstream !v directory contains an invalid '!' for generated module names,
    # so install its complete closure through the explicit module below.
    voices = [name for name in files if name.startswith(VOICES_DIR)]
    if not voices:
        raise ValueError('Missing espeak variant voice files')
    for name in files:
        if name not in voices:
            installed_model_name(name)
    files = [name for name in files if name not in voices]
    lines = ['# Generated by prepare-rom.py --write-lock; reviewed model paths only.',
             'ifneq ($(filter userdebug eng,$(TARGET_BUILD_VARIANT)),)', 'PRODUCT_COPY_FILES += \\']
    for index, name in enumerate(files):
        line = f'    vendor/taku/{PREFIX}prebuilt/models/{name}:$(TARGET_COPY_OUT_SYSTEM_EXT)/etc/taku-audio/models/{name}'
        lines.append(line + (' \\' if index + 1 < len(files) else ''))
    return '\n'.join([*lines, 'endif', ''])


def voice_blueprint(files):
    voices = [name for name in files if name.startswith(VOICES_DIR)]
    if not voices:
        raise ValueError('Missing espeak variant voice files')
    lines = [
        '// Generated by prepare-rom.py --write-lock; sources stay within this package.',
        'prebuilt_etc {',
        '    name: "taku-audio-v-voices",',
        '    srcs: [',
    ]
    lines += [f'        {json.dumps("models/" + installed_model_name(name))},' for name in voices]
    lines += ['    ],', '    dsts: [']
    lines += [f'        {json.dumps("taku-audio/models/" + installed_model_name(name))},' for name in voices]
    lines += ['    ],', '    system_ext_specific: true,', '}', '']
    return '\n'.join(lines)


def validate_source_inputs(root, lock):
    if lock['schema'] != 'taku.audio-rom-input/1' or set(lock['sourceInputs']) != set(source_names(root)):
        raise ValueError('Audio source input closure changed; rebuild and refresh the release lock')
    for name, expected in lock['sourceInputs'].items():
        if sha(ordinary(root, name)) != expected:
            raise ValueError('Audio source input changed: ' + name)


def validate_inputs(root, lock):
    validate_source_inputs(root, lock)
    expected_paths = set()
    for item in lock['assets']:
        name = item['path']
        if not name.startswith(PREFIX + 'prebuilt/') or name in expected_paths:
            raise ValueError('Invalid or duplicate audio asset')
        expected_paths.add(name)
        path = ordinary(root, name)
        if sha(path) != item['sha256'] or path.stat().st_size != item['bytes']:
            raise ValueError('Audio asset changed: ' + name)
    actual = {str(p.relative_to(root)) for p in (root / PREFIX / 'prebuilt').rglob('*')
              if p.is_file() and str(p.relative_to(root)) != VOICES_BLUEPRINT}
    if actual != expected_paths:
        raise ValueError('Unsealed or missing audio prebuilt file')
    if apk_entries(root / PREFIX / 'prebuilt/TakuAudioEngine.apk') != lock['apkEntries']:
        raise ValueError('Audio APK contents differ')
    return lock['assets']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write-lock', action='store_true', help='Explicitly refresh the reviewable release lock after building')
    args = parser.parse_args()
    lock_path = HERE / 'rom-input-lock.json'
    if not args.write_lock:
        validate_inputs(ROOT, json.loads(lock_path.read_text()))
        print('Locked audio ROM inputs verified')
        return
    runpy.run_path(str(HERE / 'record-build.py'))['verify']()
    sdk = Path(os.environ.get('ANDROID_SDK_ROOT', str(Path.home() / 'Library/Android/sdk')))
    tools = sdk / 'build-tools' / os.environ.get('TAKU_BUILD_TOOLS', '36.0.0')
    apk = HERE / 'out/TakuAudioEngine.apk'
    subprocess.run([str(tools / 'apksigner'), 'verify', str(apk)], check=True)
    badging = subprocess.check_output([str(tools / 'aapt2'), 'dump', 'badging', str(apk)], text=True)
    identity = re.search(r"^package: name='([^']+)' versionCode='(\d+)' versionName='([^']+)'", badging, re.M)
    if not identity or identity[1] != 'org.agentos.audio':
        raise ValueError('Wrong audio package')
    if "launchable-activity: name='org.agentos.audio.AudioHomeActivity'" not in badging:
        raise ValueError('Taku Audio must include its launcher-visible AudioHomeActivity')
    xml = subprocess.check_output([str(tools / 'aapt2'), 'dump', 'xmltree', str(apk), '--file', 'AndroidManifest.xml'], text=True)
    if not re.search(r':extractNativeLibs\([^\n]+\)=false', xml):
        raise ValueError('Native extraction must be disabled')
    contents = apk_entries(apk)
    pack = HERE / 'out/model-pack'
    manifest = json.loads((pack / 'manifest.json').read_text())
    models = [entry['path'] for entry in manifest['files']]
    if len(models) != len(set(models)) or not {'tts/model.onnx', 'asr/tokens.txt', 'asr-zh/tokens.txt', 'vad/silero_vad.onnx'} <= set(models):
        raise ValueError('ROM requires both recognition languages, TTS and the standby VAD')
    for entry in manifest['files']:
        path = ordinary(pack, entry['path'])
        if sha(path) != entry['sha256'] or path.stat().st_size != entry['size']:
            raise ValueError('Model manifest mismatch: ' + entry['path'])
    model_names = sorted([*models, 'manifest.json'])
    (HERE / 'models/rom-files.mk').write_text(model_makefile(model_names))
    # Rebuild staging atomically; never mix new and previous model releases.
    staging = HERE / 'out/rom-staging'
    if staging.exists():
        shutil.rmtree(staging)
    staging.mkdir()
    shutil.copyfile(apk, staging / 'TakuAudioEngine.apk')
    shutil.copyfile(HERE / 'out/audio-bridge.jar', staging / 'audio-bridge.jar')
    for name in model_names:
        target = staging / 'models' / installed_model_name(name)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(pack / name, target)
    assets = []
    for path in sorted(staging.rglob('*')):
        if path.is_file():
            path.chmod(0o644)
            assets.append({'path': PREFIX + 'prebuilt/' + str(path.relative_to(staging)),
                           'sha256': sha(path), 'bytes': path.stat().st_size})
    target = HERE / 'prebuilt'
    if target.exists():
        shutil.rmtree(target)
    staging.rename(target)
    (target / 'Android.bp').write_text(voice_blueprint(model_names))
    lock = {'schema': 'taku.audio-rom-input/1', 'package': identity[1], 'versionCode': int(identity[2]),
            'versionName': identity[3], 'sourceInputs': {name: sha(ordinary(ROOT, name)) for name in source_names(ROOT)},
            'assets': assets, 'apkEntries': contents, 'credentialsIncluded': False,
            'models': 'Bundled read-only system_ext ASR en/zh and Kokoro; no first-boot data copy'}
    validate_inputs(ROOT, lock)
    lock_path.write_text(json.dumps(lock, indent=2) + '\n')
    print(f'Sealed {len(assets)} assets; {sum(x["bytes"] for x in assets)} bytes. Review rom-input-lock.json.')


if __name__ == '__main__':
    main()
